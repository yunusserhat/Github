/* SokakPuan — local, static perception atlas. Map geometry and score provenance
   are generated by scripts/build_perception_city.py. No runtime model/API. */
"use strict";
(() => {
  const $ = id => document.getElementById(id);
  const fmt = (n, decimals = 0) => n === null || n === undefined || !Number.isFinite(Number(n)) ? "—" : Number(n).toLocaleString("tr-TR", { maximumFractionDigits: decimals, minimumFractionDigits: decimals });
  const labels = { safer: "Güvenli hissettirme", livelier: "Canlılık", more_beautiful: "Estetik", wealthier: "Varlıklı görünme", more_boring: "Sıkıcılık", more_depressing: "Bunaltıcılık" };
  const order = Object.keys(labels);
  const palette = ["#ac5751", "#d0a16b", "#d7cda1", "#8db2a1", "#267669"];
  const palePalette = ["#d2b8ae", "#dbcbb0", "#e0dcc3", "#bbd0c0", "#95b8a7"];
  const state = { key: "safer", is3d: true, selected: null, school: "all", map: null, data: null, dimensions: [], ready: false };
  const reducedMotion = matchMedia("(prefers-reduced-motion: reduce)").matches;
  const duration = reducedMotion ? 0 : 1000;
  const statusText = {
    frontage_ambiguous: "İki yol binaya yaklaşık eşit uzaklıkta. Cephe bağlamı belirsiz olduğu için renk atanmadı.",
    junction_only: "En yakın yolun görüntüleri kavşak ucunda toplanıyor. Bu kesimden puan aktarılmadı.",
    no_bin_within_radius: "En yakın yolda, binaya 30 metre içinde uygun bir gözlem dilimi bulunamadı.",
    road_beyond_radius: "En yakın yol bina tabanına 30 metreden uzak. Puan aktarılmadı.",
    road_unobserved: "En yakın yol için kullanılabilir gözlem yok. Komşu sokaktan puan taşınmadı.",
    single_panorama: "Bu renk tek bir panoramaya dayanıyor; sınırlı gözlemi göstermek için soluk çiziliyor.",
    assigned: "Renk, en yakın yolun tek bir gözlem diliminden geliyor. Aynı binaya ait bir cephe ölçümü değildir."
  };

  function dimension() { return state.dimensions.find(d => d.key === state.key); }
  function colorExpression(pale = false) {
    const d = dimension();
    const colors = [...(pale ? palePalette : palette)];
    if (d.inverse) colors.reverse();
    const lo = d.p05, hi = d.p95 > lo ? d.p95 : lo + 1;
    const expr = ["interpolate", ["linear"], ["coalesce", ["get", state.key], lo]];
    colors.forEach((c, i) => expr.push(lo + (hi - lo) * i / 4, c));
    return expr;
  }
  function buildingColor() {
    return ["case", ["==", ["get", "score_status"], "unscored"], "#c7c9c0", ["==", ["get", "score_status"], "sparse"], colorExpression(true), colorExpression()];
  }
  function makeStyle() {
    return {
      version: 8,
      sources: {},
      light: { anchor: "viewport", color: "#fffdf3", intensity: .38, position: [1.4, 200, 45] },
      layers: [{ id: "background", type: "background", paint: { "background-color": "#e9e7de" } }]
    };
  }
  function initLayers() {
    const map = state.map, data = state.data;
    ["roads", "schools", "bins"].forEach(name => map.addSource(name, { type: "geojson", data: data[name] }));
    map.addSource("buildings", { type: "geojson", data: data.buildings, promoteId: "building_id" });
    map.addLayer({ id: "school-fill", type: "fill", source: "schools", paint: { "fill-color": "#d0dac3", "fill-opacity": .65 } });
    map.addLayer({ id: "road-casing", type: "line", source: "roads", paint: { "line-color": "#d2d4c8", "line-width": ["interpolate", ["linear"], ["zoom"], 13, 2, 17, 10, 20, 50] } });
    map.addLayer({ id: "road-fill", type: "line", source: "roads", paint: { "line-color": "#faf8f0", "line-width": ["interpolate", ["linear"], ["zoom"], 13, 1, 17, 8, 20, 45] } });
    map.addLayer({ id: "school-outline", type: "line", source: "schools", paint: { "line-color": "#6b8877", "line-width": 1.1, "line-dasharray": [3, 3] } });
    map.addLayer({ id: "observation-bins", type: "line", source: "bins", paint: { "line-color": colorExpression(), "line-width": ["interpolate", ["linear"], ["zoom"], 14, 1.3, 17, 3.5, 20, 9], "line-opacity": .82 } });
    map.addLayer({ id: "selected-source-bin", type: "line", source: "bins", filter: ["==", ["get", "bin_id"], ""], paint: { "line-color": "#173f32", "line-width": 6, "line-gap-width": 2 } });
    map.addLayer({ id: "buildings-flat", type: "fill", source: "buildings", layout: { visibility: "none" }, paint: { "fill-color": buildingColor(), "fill-outline-color": "#a9b3a5", "fill-opacity": .98 } });
    map.addLayer({ id: "buildings-3d", type: "fill-extrusion", source: "buildings", paint: { "fill-extrusion-color": buildingColor(), "fill-extrusion-height": ["get", "height_m"], "fill-extrusion-base": 0, "fill-extrusion-opacity": .97, "fill-extrusion-vertical-gradient": true } });
    map.addLayer({ id: "selected-outline", type: "line", source: "buildings", filter: ["==", ["get", "building_id"], ""], paint: { "line-color": "#103d32", "line-width": 3 } });
    for (const name of ["buildings-3d", "buildings-flat"]) {
      map.on("click", name, e => {
        if (e.features.length) selectBuilding(e.features[0].properties.building_id);
      });
      map.on("mouseenter", name, () => { map.getCanvas().style.cursor = "pointer"; });
      map.on("mouseleave", name, () => { map.getCanvas().style.cursor = ""; });
    }
  }
  function selectDimension(key) {
    state.key = key;
    document.querySelectorAll(".dimension").forEach(b => { const active = b.dataset.key === key; b.classList.toggle("active", active); b.setAttribute("aria-pressed", active); });
    const d = dimension(), colors = [...palette];
    if (d.inverse) colors.reverse();
    $("metric-index").textContent = `${String(order.indexOf(key) + 1).padStart(2, "0")} / 06`;
    $("legend-title").textContent = labels[key];
    $("legend-min").textContent = `${fmt(d.p05, 2)} · düşük`;
    $("legend-max").textContent = `${fmt(d.p95, 2)} · yüksek`;
    $("legend-gradient").style.background = `linear-gradient(90deg,${colors.join(",")})`;
    $("legend-description").textContent = d.inverse ? "Yüksek ham puan, daha olumsuz algı tahmini demektir. Renkler gözlenen dağılımın %5–%95 aralığını kullanır." : "Ham model puanı · renkler gözlenen dağılımın %5–%95 aralığını kullanır; uç değerler aynı renkte kalır.";
    if (state.ready) {
      state.map.setPaintProperty("buildings-3d", "fill-extrusion-color", buildingColor());
      state.map.setPaintProperty("buildings-flat", "fill-color", buildingColor());
      state.map.setPaintProperty("observation-bins", "line-color", colorExpression());
    }
    if (state.selected) renderDetail();
  }
  function renderDimensions() {
    order.forEach(key => {
      const b = document.createElement("button"); b.className = "dimension"; b.dataset.key = key; b.textContent = labels[key]; b.setAttribute("aria-pressed", "false"); b.addEventListener("click", () => selectDimension(key)); $("dimensions").append(b);
    });
    selectDimension(state.key);
  }
  function shortSchoolName(name) {
    return name.replace("Esatpaşa Anadolu İmam Hatip Lisesi", "Esatpaşa AİHL").replace("Mehmet Rauf Anadolu Lisesi", "Mehmet Rauf AL").replace("Ali Nihat Tarlan İlkokulu", "Ali Nihat Tarlan İO");
  }
  function renderSchools() {
    // Keep the two adjoining schools together, followed by the reference area.
    const schools = [...state.data.metadata.schools].sort((a, b) => a.center[1] - b.center[1]);
    schools.forEach((school, i) => {
      const b = document.createElement("button"); b.className = "school-button"; b.dataset.school = school.id; b.setAttribute("aria-pressed", "false"); b.title = school.name;
      const n = document.createElement("span"); n.className = "school-number"; n.textContent = i + 1;
      const text = document.createElement("span"); text.textContent = shortSchoolName(school.name); b.append(n, text); $("schools").append(b);
      const marker = document.createElement("button"); marker.className = "school-marker"; marker.title = `${school.name} çevresine odaklan`; marker.setAttribute("aria-label", marker.title);
      const dot = document.createElement("span"); dot.className = "school-marker-dot"; dot.textContent = i + 1;
      const label = document.createElement("span"); label.className = "school-marker-label"; label.textContent = shortSchoolName(school.name); marker.append(dot, label); marker.addEventListener("click", () => focusSchool(school.id));
      new maplibregl.Marker({ element: marker, anchor: "bottom" }).setLngLat(school.center).addTo(state.map);
    });
    $("schools").addEventListener("click", e => { const b = e.target.closest("[data-school]"); if (b) focusSchool(b.dataset.school); });
  }
  function fitCamera(school = null) {
    const mobile = innerWidth <= 760;
    const schools = state.data.metadata.schools;
    const bounds = school ? school.bounds : [Math.min(...schools.map(s => s.bounds[0])), Math.min(...schools.map(s => s.bounds[1])), Math.max(...schools.map(s => s.bounds[2])), Math.max(...schools.map(s => s.bounds[3]))];
    state.map.fitBounds([[bounds[0], bounds[1]], [bounds[2], bounds[3]]], {
      padding: mobile ? { top: school ? 125 : 105, bottom: 235, left: 30, right: 25 } : { top: 175, bottom: 160, left: innerWidth > 1100 ? 365 : 320, right: 95 },
      maxZoom: school ? 17.4 : 16.3, pitch: state.is3d ? 53 : 0, bearing: state.is3d ? -27 : 0, duration
    });
  }
  function focusSchool(id) {
    state.school = id;
    document.querySelectorAll("[data-school]").forEach(b => { const active = b.dataset.school === id; b.classList.toggle("active", active); b.setAttribute("aria-pressed", active); });
    fitCamera(id === "all" ? null : state.data.metadata.schools.find(s => s.id === id));
  }
  function selectBuilding(id) {
    state.selected = id;
    state.map.setFilter("selected-outline", ["==", ["get", "building_id"], id]);
    const binIds = state.data.mappings.buildings[id]?.bin_ids || [];
    state.map.setFilter("selected-source-bin", ["in", ["get", "bin_id"], ["literal", binIds]]);
    renderDetail();
  }
  function renderDetail() {
    const f = state.buildingIndex.get(state.selected); if (!f) return;
    const p = f.properties, d = dimension(), scored = p.score_status !== "unscored";
    $("detail").hidden = false;
    $("detail-title").textContent = p.name || p.street_name || "Sokak çevresindeki bina";
    $("detail-id").textContent = `${p.building_id} · ${p.school_names.length ? p.school_names.join(" / ") : "Okul çevresi"}`;
    $("detail-score").textContent = scored ? fmt(p[state.key], 2) : "—";
    $("detail-metric").textContent = `${labels[state.key]} · ham model puanı`;
    $("detail-status").textContent = statusText[p.assignment_status] || "Bu bina için uygun gözlem eşleşmesi yok.";
    const heights = { tagged_height: "OSM yükseklik etiketi", overture_height: "Overture metre alanı", levels_x3: "OSM kat sayısı × 3 m", overture_num_floors_x3: "Overture kat sayısı × 3 m", display_default_6m: "gösterim için varsayılan" };
    const sourceBin = state.binIndex.get(state.data.mappings.buildings[p.building_id]?.bin_ids[0]);
    const binLength = sourceBin ? sourceBin.properties.end_m - sourceBin.properties.start_m : null;
    const fields = [
      ["Yakın sokak", p.street_name || "Adsız yol"],
      ["Gözlem dilimi", scored ? `${fmt(p.bin_count)} dilim · ${fmt(binLength, 1)} m` : "Eşleşmedi"],
      ["Panorama", scored ? fmt(p.image_count) : "—"],
      ["Çekim serisi", scored ? fmt(p.sequence_count) : "—"],
      ["Bina–dilim mesafesi", scored ? `${fmt(p.distance_m, 1)} m` : "—"],
      ["Çizim yüksekliği", `${fmt(p.height_m, Number.isInteger(p.height_m) ? 0 : 1)} m`],
      ["Yükseklik kaynağı", heights[p.height_source] || p.height_source]
    ];
    if (state.data.metadata.overture?.enabled) {
      fields.push(["Overture eşleşmesi", p.overture_id ? `%${fmt(p.overture_match_iou * 100, 1)} geometrik örtüşme` : "Kesin eşleşme yok"]);
      if (p.overture_num_floors > 0) fields.push(["Overture kat kaydı", `${fmt(p.overture_num_floors)} kat`]);
      if (p.overture_height_m > 0) fields.push(["Overture metre kaydı", `${fmt(p.overture_height_m, 1)} m`]);
    }
    $("detail-facts").replaceChildren();
    fields.forEach(([key, value]) => { const dt = document.createElement("dt"), dd = document.createElement("dd"); dt.textContent = key; dd.textContent = value; $("detail-facts").append(dt, dd); });
    $("detail-metrics").replaceChildren();
    if (scored) order.forEach(key => {
      const item = state.dimensions.find(d => d.key === key), row = document.createElement("div"); row.className = "mini-row";
      const name = document.createElement("span"); name.textContent = labels[key];
      const track = document.createElement("div"); track.className = "mini-track";
      const fill = document.createElement("div"); fill.className = "mini-fill"; fill.style.width = `${Math.max(0, Math.min(1, (p[key] - item.min) / Math.max(.001, item.max - item.min))) * 100}%`; fill.style.background = item.inverse ? "#ad7055" : "#267669";
      track.append(fill); const value = document.createElement("span"); value.className = "mini-value"; value.textContent = fmt(p[key], 2); row.append(name, track, value); $("detail-metrics").append(row);
    });
    const evidence = $("evidence"); evidence.replaceChildren();
    const images = state.data.mappings.buildings[p.building_id]?.image_ids || [];
    if (images.length) {
      const h3 = document.createElement("h3"); h3.textContent = "Kaynak panoramalar · Mapillary"; const links = document.createElement("div"); links.className = "evidence-links";
      const show = images.length <= 6 ? images : [images[0], images[Math.floor(images.length / 4)], images[Math.floor(images.length / 2)], images[Math.floor(images.length * 3 / 4)], images[images.length - 1]];
      show.forEach((id, i) => { const a = document.createElement("a"), image = state.data.mappings.images[id]; a.textContent = `Görüntü ${i + 1} ↗`; a.href = image?.mapillary_url || `https://www.mapillary.com/app/?pKey=${encodeURIComponent(id)}`; a.target = "_blank"; a.rel = "noopener"; a.title = id; links.append(a); });
      const note = document.createElement("p"); note.className = "small muted"; note.textContent = "Puan dört yönün ortalamasıdır. Kareler bağımsız katılımcı değerlendirmeleri değildir."; evidence.append(h3, links, note);
    }
    $("osm-link").href = `https://www.openstreetmap.org/${p.building_id}`;
  }
  function setupMethod() {
    const c = state.data.metadata.counts;
    $("method-data").replaceChildren(); const wrap = document.createElement("div"); wrap.className = "method-stats";
    [[c.source_panoramas, "kaynak panorama"], [c.clean_panoramas, "eşleştirmesi temiz panorama"], [c.clean_bins, "20 metrelik gözlem dilimi"], [c.excluded_union_panoramas, "belirsiz / kavşak kaynaklı, dışlanan panorama"]].forEach(([value, label]) => { const div = document.createElement("div"), strong = document.createElement("strong"), span = document.createElement("span"); strong.textContent = fmt(value); span.textContent = label; div.append(strong, span); wrap.append(div); }); $("method-data").append(wrap);
    const hs = c.height_sources;
    const parts = [];
    if (hs.tagged_height) parts.push(`${fmt(hs.tagged_height)} binada OSM metre kaydı`);
    if (hs.overture_height) parts.push(`${fmt(hs.overture_height)} binada Overture metre kaydı`);
    if (hs.levels_x3) parts.push(`${fmt(hs.levels_x3)} binada OSM kat sayısı × 3 m tahmini`);
    if (hs.overture_num_floors_x3) parts.push(`${fmt(hs.overture_num_floors_x3)} binada Overture kat sayısı × 3 m tahmini`);
    if (hs.display_default_6m) parts.push(`${fmt(hs.display_default_6m)} binada 6 m gösterim varsayımı`);
    $("height-note").textContent = `${parts.join("; ")}. Metre kaydının bulunması tek başına ölçülmüş yükseklik garantisi değildir. Her binanın kartında kullanılan kaynak belirtilir.`;
    const o = state.data.metadata.overture;
    $("overture-section").hidden = !o?.enabled;
    $("overture-credit").hidden = !o?.enabled;
    if (o?.enabled) {
      $("overture-note").textContent = `${o.release} sürümünden bu alana ait ${fmt(o.input_count)} bina kaydı alındı. Metre cinsinden yükseklik ${fmt(o.input_height_count)} kayıtta, kat sayısı ${fmt(o.input_floor_count)} kayıtta mevcut. Mevcut tabanlarla ${fmt(o.matched_buildings)} bina eşleşti.`;
      const updates = (o.applied_height_count || 0) + (o.applied_floor_count || 0);
      $("overture-result").textContent = updates ? `${fmt(updates)} binanın çizim yüksekliği Overture verisiyle tamamlandı. Veri bulunmayanlarda açıkça belirtilen gösterim yüksekliği korunur.` : "Bu alan için ek yükseklik bulunmadı. Eşleşen Overture kaydı ve kat bilgisi bina kartlarında görülebilir; mevcut yükseklikler korunur.";
    }
  }
  function setupControls() {
    $("method-open").addEventListener("click", () => $("method-dialog").showModal());
    $("method-close").addEventListener("click", () => $("method-dialog").close());
    $("method-dialog").addEventListener("click", e => { if (e.target === $("method-dialog")) { const r = e.target.getBoundingClientRect(); if (e.clientX < r.left || e.clientX > r.right || e.clientY < r.top || e.clientY > r.bottom) e.target.close(); } });
    $("detail-close").addEventListener("click", () => { $("detail").hidden = true; state.selected = null; state.map.setFilter("selected-outline", ["==", ["get", "building_id"], ""]); state.map.setFilter("selected-source-bin", ["==", ["get", "bin_id"], ""]); });
    $("show-bins").addEventListener("change", e => state.map.setLayoutProperty("observation-bins", "visibility", e.target.checked ? "visible" : "none"));
    $("only-colored").addEventListener("change", e => { const f = e.target.checked ? ["!=", ["get", "score_status"], "unscored"] : null; for (const id of ["buildings-flat", "buildings-3d"]) state.map.setFilter(id, f); });
    [true, false].forEach(is3d => $(is3d ? "view-3d" : "view-2d").addEventListener("click", () => {
      state.is3d = is3d;
      $("view-3d").classList.toggle("active", is3d); $("view-2d").classList.toggle("active", !is3d); $("view-3d").setAttribute("aria-pressed", is3d); $("view-2d").setAttribute("aria-pressed", !is3d);
      state.map.setLayoutProperty("buildings-3d", "visibility", is3d ? "visible" : "none"); state.map.setLayoutProperty("buildings-flat", "visibility", is3d ? "none" : "visible"); state.map.easeTo({ pitch: is3d ? 53 : 0, bearing: is3d ? -27 : 0, duration });
    }));
    $("zoom-in").addEventListener("click", () => state.map.zoomIn({ duration: reducedMotion ? 0 : 250 }));
    $("zoom-out").addEventListener("click", () => state.map.zoomOut({ duration: reducedMotion ? 0 : 250 }));
    $("reset-map").addEventListener("click", () => focusSchool("all"));
  }
  async function start() {
    try {
      const files = ["metadata.json", "buildings.geojson", "roads.geojson", "schools.geojson", "bins.geojson", "mappings.json"];
      const items = await Promise.all(files.map(async file => { const r = await fetch(`data/${file}`); if (!r.ok) throw new Error(`${file}: HTTP ${r.status}`); return r.json(); }));
      state.data = Object.fromEntries(files.map((f, i) => [f.split(".")[0], items[i]]));
      state.dimensions = state.data.metadata.dimensions;
      state.buildingIndex = new Map(state.data.buildings.features.map(f => [f.properties.building_id, f]));
      state.binIndex = new Map(state.data.bins.features.map(f => [f.properties.bin_id, f]));
      const counts = state.data.metadata.counts;
      $("colored-count").textContent = fmt(counts.buildings_scored + counts.buildings_sparse); $("building-count").textContent = fmt(counts.buildings);
      renderDimensions();
      state.map = new maplibregl.Map({ container: "map", style: makeStyle(), center: [29.0832, 41.0041], zoom: 16, pitch: 53, bearing: -27, maxPitch: 75, minZoom: 13.5, maxZoom: 20.5, attributionControl: false, fadeDuration: 0, canvasContextAttributes: { preserveDrawingBuffer: true }, maxBounds: [[29.067, 40.989], [29.102, 41.02]] });
      state.map.addControl(new maplibregl.ScaleControl({ maxWidth: 90, unit: "metric" }), "bottom-left");
      state.map.on("error", e => { console.error("Map error:", e.error); });
      await new Promise(resolve => state.map.once("load", resolve));
      initLayers(); state.ready = true; renderSchools(); setupMethod(); setupControls();
      fitCamera();
      await new Promise(resolve => state.map.once("idle", resolve));
      $("loading").hidden = true;
      // Expose read-only data references and a selection action for inspection/QA.
      window.SokakPuan = { get map() { return state.map; }, get metadata() { return state.data.metadata; }, get buildings() { return state.data.buildings; }, selectBuilding, get dimension() { return state.key; } };
    } catch (error) {
      console.error(error); $("loading").hidden = true; $("error").hidden = false;
      $("error").textContent = `Harita hazırlanamadı. Sayfayı yerel sunucu üzerinden açın ve veri dosyalarını kontrol edin. ${error.message}`;
    }
  }
  start();
})();
